/**
 * Runs bounded real-pipeline mock teleports and exports their landing heatmap.
 */
public final class TestTeleportHeatmapCmd extends BaseRTPCmdImpl {
    private static final String OWNER = "test.heatmap";
    private static final String LOG_PREFIX = "[RTP test/teleport-heatmap] ";

    public static final BitCode HEATMAP_MOCKED = RtpBitCodes.HEATMAP.register(
            4700, "HEATMAP_MOCKED", System.Logger.Level.INFO, BitTier.IBIT, OWNER, "",
            "Heatmap results are generated by synthetic BIT players, not real accounts.");
    public static final BitCode HEATMAP_UNAVAILABLE = RtpBitCodes.HEATMAP.register(
            4701, "HEATMAP_UNAVAILABLE", System.Logger.Level.ERROR, BitTier.IBIT, OWNER,
            "", "Load RTP and select a region whose world is available.");
    public static final BitCode HEATMAP_TELEPORT_FAILED = RtpBitCodes.HEATMAP.register(
            4702, "HEATMAP_TELEPORT_FAILED", System.Logger.Level.ERROR, BitTier.IBIT, OWNER,
            "", "Inspect the RTP pipeline failure and retry the heatmap probe.");
    public static final BitCode HEATMAP_LANDING_MISSING = RtpBitCodes.HEATMAP.register(
            4703, "HEATMAP_LANDING_MISSING", System.Logger.Level.ERROR, BitTier.IBIT, OWNER,
            "", "Verify that successful mock landings are appended to BitTeleportLog.");
    public static final BitCode HEATMAP_EXPORT_FAILED = RtpBitCodes.HEATMAP.register(
            4704, "HEATMAP_EXPORT_FAILED", System.Logger.Level.ERROR, BitTier.IBIT, OWNER,
            "", "Check the plugin data folder is writable and rerun the probe.");
    public static final BitCode HEATMAP_CANCELLED = RtpBitCodes.HEATMAP.register(
            4705, "HEATMAP_CANCELLED", System.Logger.Level.WARNING, BitTier.IBIT, OWNER,
            "", "Rerun the named probe after the current test is no longer cancelled.");

    static final String DEFAULT_REGION = "default";
    static final int MIN_SAMPLES = 1;
    static final int DEFAULT_SAMPLES = 64;
    static final int MAX_SAMPLES = 256;
    static final int BIN_SIZE = 128;
    static final long COMPONENT_TIMEOUT_MILLIS = 300_000L;

    public static final BitComponent COMPONENT = registerComponent();

    @FunctionalInterface
    interface TeleportFn {
        CompletableFuture<RTPResult> apply(UUID player, RtpTarget target);
    }

    public TestTeleportHeatmapCmd(@Nullable CommandsAPICommand parent) {
        super(parent);
        addParameter("region", new RegionParameter("rtp.test", "region to sample", (uuid, value) -> value != null && !value.isBlank()));
        addParameter("samples", new IntegerParameter("rtp.test", "number of mock teleports (1-256)",
                (uuid, value) -> isInteger(value), MIN_SAMPLES, DEFAULT_SAMPLES, MAX_SAMPLES));
        addParameter("json", new BooleanParameter("rtp.test", "emit the BIT report as JSON", (uuid, value) -> true));
    }

    @Override
    public String name() {
        return "teleport-heatmap";
    }

    @Override
    public String permission() {
        return "rtp.test.mutating";
    }

    @Override
    public String description() {
        return "sample mock RTP teleports and export a landing heatmap";
    }

    @Override
    public boolean onCommand(
            UUID callerId,
            Map<String, List<String>> parameterValues,
            CommandsAPICommand nextCommand) {
        if (nextCommand != null) return true;
        UUID owner = callerId != null ? callerId : RTPAPI.serverId;

        TestSemaphore.Holder holder = TestSemaphore.holderOf(owner);
        boolean parentHeld = holder != null && name().equals(holder.subName);
        if (!parentHeld && !TestSemaphore.tryAcquire(owner, name())) {
            reportBusy(owner);
            return false;
        }

        int samples = samples(parameterValues);
        String region = region(parameterValues);
        AtomicBoolean cancelled = new AtomicBoolean();
        AtomicBoolean timedOut = new AtomicBoolean();
        AtomicReference<MockPlayerSession> activeSession = new AtomicReference<>();
        Runnable unregister = ActiveTestJobs.register(
                owner, new ActiveTestJobs.Job(name(), () -> cancelled.set(true)));
        CompletableFuture<BitReport> report = new CompletableFuture<>();
        ProbeVerdict.record(COMPONENT, report, COMPONENT_TIMEOUT_MILLIS)
                .whenComplete((result, failure) -> finishCommand(
                        owner, parameterValues, result, failure, cancelled, timedOut, activeSession, unregister, parentHeld));

        RTPScheduler scheduler = RTPRuntime.scheduler();
        if (scheduler == null) {
            report.complete(unavailableReport("RTP.scheduler is unavailable."));
            return true;
        }
        try {
            scheduler.runTaskAsynchronously(() -> {
                Probe probe = new Probe(
                        region, samples, RTPAPI::teleport, scheduler, report, cancelled, timedOut, activeSession);
                try {
                    probe.start();
                } catch (Throwable failure) {
                    probe.fail(HEATMAP_UNAVAILABLE, "heatmap.start", "Could not start probe: " + failure);
                    probe.finish(false);
                }
            });
        } catch (Throwable failure) {
            report.complete(unavailableReport("Could not schedule probe: " + failure));
            RTPRuntime.log(Level.WARNING, LOG_PREFIX + "could not schedule probe", failure);
        }
        return true;
    }

    static int samples(@Nullable Map<String, List<String>> parameters) {
        List<String> values = parameters == null ? null : parameters.get("samples");
        if (values == null || values.isEmpty() || values.get(0) == null) return DEFAULT_SAMPLES;
        try {
            int requested = Integer.parseInt(values.get(0).trim());
            return Math.max(MIN_SAMPLES, Math.min(MAX_SAMPLES, requested));
        } catch (NumberFormatException ignored) {
            return DEFAULT_SAMPLES;
        }
    }

    static String region(@Nullable Map<String, List<String>> parameters) {
        List<String> values = parameters == null ? null : parameters.get("region");
        if (values == null || values.isEmpty() || values.get(0) == null || values.get(0).isBlank()) {
            return DEFAULT_REGION;
        }
        return values.get(0);
    }

    private static boolean isInteger(String value) {
        if (value == null) return false;
        try {
            Integer.parseInt(value.trim());
            return true;
        } catch (NumberFormatException ignored) {
            return false;
        }
    }

    private static BitComponent registerComponent() {
        return new BitComponent(
                "teleport-heatmap", OWNER, BitTier.IBIT, BitSideEffect.HEAVY,
                COMPONENT_TIMEOUT_MILLIS,
                () -> ProbeBitReport.forProbe("teleport-heatmap")
                        .note(HEATMAP_MOCKED, "heatmap.mocked", "No real player is teleported by this probe.")
                        .build());
    }

    private static BitReport unavailableReport(String detail) {
        return failureReport(HEATMAP_UNAVAILABLE, "heatmap.region", detail);
    }

    static BitReport failureReport(BitCode code, String path, String detail) {
        ProbeBitReport.Builder report = ProbeBitReport.forProbe(COMPONENT.id());
        recordFailure(report, code, path, detail);
        report.note(HEATMAP_MOCKED, "heatmap.mocked", "No real player is teleported by this probe.");
        return report.build();
    }

    private static void recordFailure(ProbeBitReport.Builder report, BitCode code, String path, String detail) {
        report.check(code, false, path, detail);
        RTPRuntime.log(Level.WARNING, LOG_PREFIX + code.key() + ": " + detail);
    }

    private static void finishCommand(
            UUID callerId,
            Map<String, List<String>> parameters,
            @Nullable BitResult result,
            @Nullable Throwable failure,
            AtomicBoolean cancelled,
            AtomicBoolean timedOut,
            AtomicReference<MockPlayerSession> activeSession,
            Runnable unregister,
            boolean parentHeld) {
        boolean componentTimedOut = failure == null
                && result != null
                && containsCode(result.report(), BitCodes.COMPONENT_TIMEOUT.key());
        if (componentTimedOut) {
            timedOut.set(true);
            cancelled.set(true);
        }
        Runnable finish = () -> {
            try {
                if (failure != null || result == null) {
                    RTPRuntime.log(Level.WARNING, LOG_PREFIX + "BIT verdict failed", failure);
                    return;
                }
                if (componentTimedOut) closeActive(activeSession);
                BitResult complete = withMockedFinding(result);
                ProbeBitReport.emit(callerId, parameters, COMPONENT, complete);
                RTPRuntime.log(
                        complete.report().health() == BitHealth.HEALTHY ? Level.INFO : Level.WARNING,
                        LOG_PREFIX + "completed with " + complete.report().findings().size() + " finding(s)");
            } finally {
                try {
                    unregister.run();
                } finally {
                    if (!parentHeld) TestSemaphore.release(callerId, COMPONENT.id());
                }
            }
        };

        RTPScheduler scheduler = RTPRuntime.scheduler();
        if (scheduler == null) {
            finish.run();
            return;
        }
        try {
            scheduler.runTaskAsynchronously(finish);
        } catch (Throwable schedulingFailure) {
            RTPRuntime.log(Level.WARNING, LOG_PREFIX + "could not dispatch BIT verdict", schedulingFailure);
            closeActive(activeSession);
            finish.run();
        }
    }

    private static boolean containsCode(BitReport report, String key) {
        return report.findings().stream().anyMatch(finding -> finding.code().equals(key));
    }

    static BitResult withMockedFinding(BitResult result) {
        if (containsCode(result.report(), HEATMAP_MOCKED.key())) return result;
        List<BitFinding> findings = new ArrayList<>(result.report().findings());
        findings.add(BitFinding.of(
                HEATMAP_MOCKED,
                "rtp test " + COMPONENT.id(),
                "heatmap.mocked",
                "Heatmap input is limited to registered synthetic BIT mock players.",
                "mocked telemetry",
                HEATMAP_MOCKED.remediation()));
        BitReport report = BitReport.of(findings);
        return RtpBit.RUNNER.run(COMPONENT.withCheck(() -> report), Runnable::run);
    }

    private static void closeActive(AtomicReference<MockPlayerSession> activeSession) {
        MockPlayerSession session = activeSession.getAndSet(null);
        if (session != null) session.close();
    }

    private static void reportBusy(UUID callerId) {
        String message = LOG_PREFIX + "another test is already in flight for this caller";
        if (!callerId.equals(RTPAPI.serverId) && RTPRuntime.serverAccessor() != null) {
            RTPRuntime.serverAccessor().sendMessage(callerId, "&c" + message);
        }
        RTPRuntime.log(Level.WARNING, message);
    }

    private static final class Probe {
        private final String regionName;
        private final int samples;
        private final TeleportFn teleport;
        private final RTPScheduler scheduler;
        private final CompletableFuture<BitReport> completion;
        private final AtomicBoolean cancelled;
        private final AtomicBoolean timedOut;
        private final AtomicReference<MockPlayerSession> activeSession;
        private final ProbeBitReport.Builder report = ProbeBitReport.forProbe(COMPONENT.id());
        private final List<MockTeleportRecord> landings = new ArrayList<>();
        private final AtomicBoolean completed = new AtomicBoolean();
        private RTPWorld<?> world;
        private Path outputDirectory;

        private Probe(
                String regionName,
                int samples,
                TeleportFn teleport,
                RTPScheduler scheduler,
                CompletableFuture<BitReport> completion,
                AtomicBoolean cancelled,
                AtomicBoolean timedOut,
                AtomicReference<MockPlayerSession> activeSession) {
            this.regionName = regionName;
            this.samples = samples;
            this.teleport = teleport;
            this.scheduler = scheduler;
            this.completion = completion;
            this.cancelled = cancelled;
            this.timedOut = timedOut;
            this.activeSession = activeSession;
        }

        private void start() {
            if (completion.isDone()) return;
            if (RTPRuntime.serverAccessor() == null) {
                fail(HEATMAP_UNAVAILABLE, "heatmap.region", "RTP server accessor is unavailable.");
                finish(false);
                return;
            }
            world = MockProbeWorld.resolve(regionName);
            if (world == null) {
                fail(HEATMAP_UNAVAILABLE, "heatmap.region", "Region '" + regionName + "' has no loaded world.");
                finish(false);
                return;
            }
            File dataDirectory = RTPRuntime.serverAccessor().getPluginDirectory();
            if (dataDirectory == null) {
                fail(HEATMAP_UNAVAILABLE, "heatmap.output", "Plugin data folder is unavailable.");
                finish(false);
                return;
            }
            outputDirectory = dataDirectory.toPath().resolve("reports/adr-121/teleport-heatmap");
            next(0);
        }

        private void next(int index) {
            if (completion.isDone() || timedOut.get()) return;
            if (cancelled.get()) {
                fail(HEATMAP_CANCELLED, "heatmap.cancel", "Probe was cancelled after " + index + " sample(s).");
                finish(true);
                return;
            }
            if (index >= samples) {
                finish(true);
                return;
            }

            MockPlayerSession session;
            try {
                session = MockPlayerSession.open(MockProbeWorld.spawn(world));
                activeSession.set(session);
            } catch (Throwable failure) {
                fail(HEATMAP_TELEPORT_FAILED, "heatmap.mock", "Could not open mock session: " + failure);
                next(index + 1);
                return;
            }

            RuntimeMockRTPPlayer mock = session.player();
            CompletableFuture<RTPResult> future;
            try {
                future = teleport.apply(mock.uuid(), RtpTarget.region(regionName));
                if (future == null) throw new IllegalStateException("RTPAPI.teleport returned a null future");
            } catch (Throwable failure) {
                close(session);
                fail(HEATMAP_TELEPORT_FAILED, "heatmap.teleport", mock.name() + ": " + failure);
                next(index + 1);
                return;
            }

            future.whenComplete((result, failure) -> dispatch(() -> completeSample(index, session, result, failure)));
        }

        private void completeSample(
                int index, MockPlayerSession session, @Nullable RTPResult result, @Nullable Throwable failure) {
            if (timedOut.get()) {
                close(session);
                return;
            }
            try {
                if (failure != null) {
                    fail(HEATMAP_TELEPORT_FAILED, "heatmap.teleport", session.player().name() + ": " + failure);
                } else if (result == null || !result.isSuccess()) {
                    fail(HEATMAP_TELEPORT_FAILED, "heatmap.teleport", session.player().name() + ": " + result);
                } else {
                    MockTeleportRecord landing = BitTeleportLog.snapshot().stream()
                            .filter(record -> record.mockId().equals(session.player().uuid()))
                            .findFirst()
                            .orElse(null);
                    if (landing == null) {
                        fail(HEATMAP_LANDING_MISSING, "heatmap.landing", session.player().name() + " landed without a BitTeleportLog record.");
                    } else {
                        landings.add(landing);
                    }
                }
            } catch (Throwable probeFailure) {
                fail(HEATMAP_TELEPORT_FAILED, "heatmap.teleport", "Could not inspect sample: " + probeFailure);
            } finally {
                close(session);
            }
            if (!completion.isDone() && !timedOut.get()) {
                if (cancelled.get()) {
                    fail(HEATMAP_CANCELLED, "heatmap.cancel", "Probe was cancelled after " + (index + 1) + " sample(s).");
                    finish(true);
                } else {
                    next(index + 1);
                }
            }
        }

        private void dispatch(Runnable task) {
            try {
                scheduler.runTaskAsynchronously(task);
            } catch (Throwable failure) {
                fail(HEATMAP_TELEPORT_FAILED, "heatmap.scheduler", "Could not schedule sample continuation: " + failure);
                closeActive(activeSession);
                finish(false);
            }
        }

        private void close(MockPlayerSession session) {
            activeSession.compareAndSet(session, null);
            session.close();
        }

        private void fail(BitCode code, String path, String detail) {
            recordFailure(report, code, path, detail);
        }

        private void finish(boolean export) {
            if (timedOut.get()) return;
            if (!completed.compareAndSet(false, true)) return;
            if (export && !completion.isDone()) {
                try {
                    BitLandingBins.Bins bins = BitLandingBins.bin(landings, BIN_SIZE, BIN_SIZE);
                    BitHeatmapExport.ExportedFiles files =
                            BitHeatmapExport.export(outputDirectory, regionName, landings, bins);
                    report.note(
                            HEATMAP_MOCKED,
                            "heatmap.mocked",
                            "Generated from " + samples + " synthetic mock teleports; " + landings.size()
                                    + " landing(s). CSV: " + files.csv() + "; PNG: " + files.png());
                } catch (Throwable failure) {
                    fail(HEATMAP_EXPORT_FAILED, "heatmap.export", "Could not write CSV/PNG: " + failure);
                    report.note(HEATMAP_MOCKED, "heatmap.mocked", "Heatmap input was limited to synthetic BIT mock players.");
                }
            } else {
                report.note(HEATMAP_MOCKED, "heatmap.mocked", "Heatmap input was limited to synthetic BIT mock players.");
            }
            completion.complete(report.build());
        }
    }
}
