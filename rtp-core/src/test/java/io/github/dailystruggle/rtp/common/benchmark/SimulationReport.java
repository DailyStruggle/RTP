package io.github.dailystruggle.rtp.common.benchmark;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;

/**
 * Collects benchmark rows and writes them to {@code build/reports/rtp-simulation} as markdown + CSV
 * (ADR-080).
 *
 * <p>Every row carries a {@link Provenance} tier. A published figure must state its tier: a live
 * measurement and a behavioural model are not the same kind of number, and blending them in one
 * table is how benchmarks become marketing.
 */
final class SimulationReport {

  /** How a number was obtained. Mandatory on every emitted row. */
  enum Provenance {
    /** Timed or counted on this machine, this run, against shipped code. */
    MEASURED,
    /** Arithmetic over MEASURED inputs, no behavioural assumption added. */
    DERIVED,
    /** Output of a behavioural cost model. Depends on assumptions, not just measurement. */
    MODELED
  }

  private record Row(String section, String subject, String metric, String value, Provenance tier) {}

  private final List<Row> rows = new ArrayList<>();
  private final List<String> notes = new ArrayList<>();

  void add(String section, String subject, String metric, String value, Provenance tier) {
    rows.add(new Row(section, subject, metric, value, tier));
    System.out.printf(
        "[DEBUG_LOG] %-22s %-26s %-34s %18s  %s%n", section, subject, metric, value, tier);
  }

  void add(String section, String subject, String metric, double value, Provenance tier) {
    add(section, subject, metric, String.format("%.3f", value), tier);
  }

  void note(String text) {
    notes.add(text);
    System.out.println("[DEBUG_LOG] note: " + text);
  }

  int size() {
    return rows.size();
  }

  /** Writes markdown + CSV. Never throws: a report-write failure must not fail the benchmark. */
  void write(String fileStem) {
    String dir = System.getProperty("rtp.simulation.reportDir");
    if (dir == null || dir.isBlank()) {
      System.out.println("[DEBUG_LOG] rtp.simulation.reportDir unset; skipping report files");
      return;
    }
    try {
      Path out = Paths.get(dir);
      Files.createDirectories(out);
      Files.writeString(
          out.resolve(fileStem + ".md"), markdown(), StandardCharsets.UTF_8);
      Files.writeString(out.resolve(fileStem + ".csv"), csv(), StandardCharsets.UTF_8);
      System.out.println("[DEBUG_LOG] report written to " + out.resolve(fileStem + ".md"));
    } catch (IOException e) {
      System.out.println("[DEBUG_LOG] report write failed: " + e);
    }
  }

  private String header() {
    return "- JVM: "
        + System.getProperty("java.vm.name")
        + " "
        + System.getProperty("java.version")
        // The JVM's own view, not what the build script believes it asked for. Allocation and
        // retained-heap figures are only comparable across runs with identical args, so the
        // args have to travel with the numbers.
        + "\n- JVM args: `"
        + String.join(" ", java.lang.management.ManagementFactory.getRuntimeMXBean().getInputArguments())
        + "`\n- Max heap: "
        + (Runtime.getRuntime().maxMemory() / (1024 * 1024))
        + " MB\n- OS: "
        + System.getProperty("os.name")
        + " "
        + System.getProperty("os.arch")
        + "\n- CPUs: "
        + Runtime.getRuntime().availableProcessors()
        + "\n- Generated: "
        + java.time.OffsetDateTime.now()
        + "\n";
  }

  private String markdown() {
    StringBuilder sb = new StringBuilder();
    sb.append("# RTP simulation benchmark\n\n");
    sb.append("Generated by `:rtp-core:simulationBenchmark` (ADR-080). Machine-relative: ");
    sb.append("absolute values are only comparable against another run on the same rig ");
    sb.append("with the same pinned JVM args.\n\n");
    sb.append("## Run environment\n\n").append(header()).append('\n');
    sb.append("## Provenance tiers\n\n");
    sb.append("| Tier | Meaning |\n|---|---|\n");
    sb.append("| `MEASURED` | Timed or counted on this machine against shipped code. |\n");
    sb.append("| `DERIVED` | Arithmetic over measured inputs. |\n");
    sb.append("| `MODELED` | Behavioural cost-model output; assumption-dependent. |\n\n");
    sb.append("## Results\n\n");
    sb.append("| Section | Subject | Metric | Value | Provenance |\n|---|---|---|---:|---|\n");
    for (Row r : rows) {
      sb.append("| ")
          .append(r.section())
          .append(" | ")
          .append(r.subject())
          .append(" | ")
          .append(r.metric())
          .append(" | ")
          .append(r.value())
          .append(" | `")
          .append(r.tier())
          .append("` |\n");
    }
    if (!notes.isEmpty()) {
      sb.append("\n## Notes\n\n");
      for (String n : notes) {
        sb.append("- ").append(n).append('\n');
      }
    }
    return sb.toString();
  }

  private String csv() {
    StringBuilder sb = new StringBuilder("section,subject,metric,value,provenance\n");
    for (Row r : rows) {
      sb.append(q(r.section()))
          .append(',')
          .append(q(r.subject()))
          .append(',')
          .append(q(r.metric()))
          .append(',')
          .append(q(r.value()))
          .append(',')
          .append(r.tier())
          .append('\n');
    }
    return sb.toString();
  }

  private static String q(String s) {
    return s.indexOf(',') < 0 ? s : '"' + s.replace("\"", "\"\"") + '"';
  }
}
