package io.github.dailystruggle.rtp.common.benchmark;

import java.util.Arrays;
import java.util.HashMap;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;

/**
 * Discrete-event queueing model of a random-teleport request path (ADR-080).
 *
 * <p><b>Why a queue and not a sum.</b> The previous tier added per-request operation costs and
 * divided. That can only ever produce the spread of the operation counts - about 2x between the
 * designs modelled - while the real harness measures a spread of several hundred fold on mean
 * latency. The missing factor is not a cost constant, it is contention: foreground chunk work
 * queues behind the tick thread, so cost per request grows with utilisation and the tail is
 * generated by the queue rather than by any single operation. A multi-second stall is a queue
 * length, not an expensive call.
 *
 * <p><b>Closed loop, paced.</b> Clients issue back-to-back requests and wait for completion, and a
 * global dispatch gate caps issue rate, mirroring the real harness. Throughput is therefore an
 * <em>output</em>, not an input, and a design can be dispatch-limited (server idle, waiting for the
 * next request) or service-limited (clients waiting for the server) without being told which.
 *
 * <p><b>Deterministic.</b> All randomness comes from {@link CandidateStream}'s pre-generated tape at
 * the same cursor positions, so two arms making the same number of draws see identical coordinates.
 * Differences are attributable to the operations an arm chose to perform.
 *
 * <p><b>What it does not model</b>, and every one of these omissions flatters the designs that do
 * more chunk work: world generation, chunk unload/save cost, JIT and GC pauses of the host JVM,
 * entity and view-distance aftershock around an arrival, and the platform-owned allocation of a
 * chunk payload. Model output is therefore a lower bound on the spread between designs.
 */
final class QueueSim {

  private QueueSim() {}

  /** Microseconds per server tick. Tick-time percentiles are bucketed at this width. */
  private static final long TICK_US = 50_000L;

  /** A region thread that is this far behind is frozen from a player's point of view. */
  private static final long FREEZE_US = 5_000_000L;

  /**
   * Per-operation costs. One instance is shared by every arm in a comparison - common random
   * numbers applied to the cost table as well as to the coordinates, so no arm can win on price.
   *
   * @param chunkLoadUs materialising one live chunk on a pregenerated world
   * @param regionReadColdUs one region-file read that misses the byte cache; MEASURED by the anvil
   *     benchmark in this same tier
   * @param binnedReadUs amortised region-file cost per candidate when selections are binned by
   *     owning region file, so a batch pays one read for many candidates
   * @param liveBlockCheckUs a safety check through the live block API, which requires the chunk
   * @param servePathUs the teleport itself once a destination is known
   * @param memoryLookupUs a spatial-memory hit: rejects a candidate with no chunk and no file read
   * @param regionHopUs Folia region-context acquisition, charged per candidate to a live-block
   *     verifier and once per served teleport to a prefilter
   * @param baseTickUs server tick cost with no plugin work at all
   */
  record Costs(
      double chunkLoadUs,
      double regionReadColdUs,
      double binnedReadUs,
      double liveBlockCheckUs,
      double servePathUs,
      double memoryLookupUs,
      double regionHopUs,
      double baseTickUs) {}

  /**
   * One design under test, described in behaviour rather than implementation.
   *
   * @param name report subject
   * @param folia region-threaded platform rather than a single tick thread
   * @param prefilterFirst answer safety from region-file bytes off-tick before materialising any
   *     chunk; the alternative is load-then-check through the live block API
   * @param binnedReads bin candidates by owning region file so a batch pays one read
   * @param durableMemory remember rejected ground across requests
   * @param memoryTtlUs expiry for remembered ground, {@code 0} for no expiry
   * @param clustered sample near the previous pick rather than uniformly
   * @param cacheDepth destination cache capacity, {@code 0} for none
   * @param asyncChunkShare fraction of chunk work served off the tick thread; the measured
   *     discriminator on the real rig
   * @param chunksPerCandidate live chunks materialised per surviving candidate, including any
   *     preload neighbourhood
   * @param maxAttempts retry budget before the request gives up
   * @param refillPulseUs interval between background cache-refill pulses
   * @param refillBudget candidate evaluations a single refill pulse is allowed
   */
  record Arm(
      String name,
      boolean folia,
      boolean prefilterFirst,
      boolean binnedReads,
      boolean durableMemory,
      long memoryTtlUs,
      boolean clustered,
      int cacheDepth,
      double asyncChunkShare,
      double chunksPerCandidate,
      int maxAttempts,
      long refillPulseUs,
      int refillBudget) {}

  /**
   * Simulation output. Latency percentiles are end to end per request, as the harness measures them.
   *
   * @param inFlight requests concurrently in the system, by Little's law - the structural check
   * @param cacheHitFraction fraction of requests served from cache; the low mode of the bimodal
   *     distribution
   * @param stallsOverOneSecond requests exceeding the thresholds an operator notices, per 1000
   * @param regionFreezes region threads observed more than five seconds behind
   */
  record Result(
      double throughputPerSecond,
      double p50Millis,
      double p95Millis,
      double p99Millis,
      double p999Millis,
      double maxMillis,
      double meanMillis,
      double msptAvgMillis,
      double msptP99Millis,
      double msptMaxMillis,
      double chunksPerRequest,
      double attemptsPerRequest,
      double inFlight,
      double cacheHitFraction,
      double stallsOverOneSecond,
      double stallsOverFiveSeconds,
      int regionFreezes,
      double unservedFraction) {}

  /** Mutable server state, kept in one place so the work helpers stay readable. */
  private static final class State {
    long mainFreeAt;
    /**
     * Tick-thread capacity consumed by background queue refill.
     *
     * <p>Separate from {@link #mainFreeAt} on purpose, and this is the most consequential
     * structural decision in the model. Background refill runs as a scheduled task with a bounded
     * per-tick budget and yields; a player's teleport is not enqueued behind the whole refill
     * backlog. Putting both in one FIFO made every request on the cached arm wait behind the
     * refiller and produced a 100 ms p50 against a measured 1 ms - the model was reporting its own
     * queue discipline as the design's latency. Background work still occupies the tick, so it
     * still shows up in MSPT, but it does not delay the request path.
     */
    long backgroundFreeAt;
    final long[] asyncFreeAt;
    final Map<Long, Long> regionFreeAt = new HashMap<>();
    /** End of the episode a region is already counted as frozen for, so one stall counts once. */
    final Map<Long, Long> regionFrozenUntil = new HashMap<>();
    final Map<Long, Long> tickBusy = new HashMap<>();
    int regionFreezes;

    State(int asyncWorkers) {
      this.asyncFreeAt = new long[Math.max(1, asyncWorkers)];
    }
  }

  /**
   * Replay a request stream through one arm.
   *
   * @param clients concurrent requesters, each waiting for its own completion before asking again
   * @param dispatchCapPerSecond harness issue-rate ceiling across all clients
   * @param asyncWorkers platform chunk-IO / plugin async parallelism
   */
  @SuppressWarnings("PMD.CognitiveComplexity")
  static Result run(
      Arm arm,
      Costs costs,
      CandidateStream stream,
      int requests,
      int clients,
      double dispatchCapPerSecond,
      int asyncWorkers) {

    stream.reset();
    State st = new State(asyncWorkers);
    long[] latency = new long[requests];
    long[] clientReady = new long[Math.max(1, clients)];
    long dispatchInterval = (long) (1_000_000.0 / Math.max(0.001, dispatchCapPerSecond));
    long nextDispatch = 0L;

    Set<Long> durable = new HashSet<>();
    Map<Long, Long> ttl = new HashMap<>();
    int tokens = 0;
    // Pipelined refill. Verified locations become available when their own work finishes, not when
    // the previous one did: a sequential refiller waits out each async chunk load in turn and caps
    // production at one per completion, which held the modelled cache-hit rate near 0.5 against a
    // measured 1 ms p50. Completion timestamps let many locations be in flight across the pool at
    // once, which is what the real filler does.
    // Priority queue, not a deque: completion times are not issued in submission order once work
    // is spread across a pool, so a FIFO would hand out locations before they exist.
    java.util.PriorityQueue<Long> pendingLocations = new java.util.PriorityQueue<>();
    long refillerAt = 0L;
    // Credit-based pacing rather than a pulse cursor. A cursor advanced by one whole period per
    // request drifts ahead of the clock as soon as requests arrive faster than the period, which
    // silently starved refill and made a cache design look like a memoryless one. Credits accrue
    // with elapsed time, so unused budget is neither lost nor manufactured.
    double refillCredits = 0.0;
    long creditedAt = 0L;
    long previousPick = 0L;

    long chunkLoads = 0L;
    long attempts = 0L;
    long hits = 0L;
    long unserved = 0L;
    long completedAt = 0L;

    for (int r = 0; r < requests; r++) {
      int ci = r % clientReady.length;
      long start = Math.max(clientReady[ci], nextDispatch);
      nextDispatch = start + dispatchInterval;

      // Background cache refill competes for the same async workers as the request path, so it is
      // advanced to the request's start time before the request is served rather than being given
      // free capacity. A refiller that never contends is a refiller that always wins.
      // Refill is paced, not greedy. The shipped queue manager fills on a scheduled pulse with a
      // bounded budget per pulse; a refiller allowed to run flat out to a deep cache saturates the
      // async pool and the tick thread, and then reports the resulting queue as the design's
      // latency. That is an artefact of the harness, not a property of the design.
      while (!pendingLocations.isEmpty() && pendingLocations.peek() <= start) {
        pendingLocations.poll();
        if (tokens < arm.cacheDepth()) tokens++;
      }

      if (arm.cacheDepth() > 0) {
        refillCredits +=
            (double) (start - creditedAt) / arm.refillPulseUs() * arm.refillBudget();
        refillCredits = Math.min(refillCredits, arm.refillBudget());
        creditedAt = start;
        while (refillCredits >= 1.0
            && refillerAt < start
            && tokens + pendingLocations.size() < arm.cacheDepth()) {
          refillCredits -= 1.0;
          long t = refillerAt;
          // Submission pacing only: the next candidate is submitted a pulse-share later regardless
          // of when this one completes.
          refillerAt = t + arm.refillPulseUs() / Math.max(1, arm.refillBudget());
          long candidate = nextCandidate(arm, stream, previousPick);
          previousPick = candidate;
          if (isRemembered(arm, durable, ttl, candidate, t)) {
            asyncWork(st, t, costs.memoryLookupUs());
            continue;
          }
          if (arm.prefilterFirst()) {
            t = asyncWork(st, t, arm.binnedReads() ? costs.binnedReadUs() : costs.regionReadColdUs());
            if (!stream.safeGround(candidate)) {
              remember(arm, durable, ttl, candidate, t);
              continue;
            }
          }
          t = chunkWork(st, arm, costs, t, arm.chunksPerCandidate(), candidate, true);
          chunkLoads += Math.round(arm.chunksPerCandidate());
          if (!arm.prefilterFirst()) {
            t = mainWork(st, arm, costs, t, costs.liveBlockCheckUs(), candidate, true);
            if (!stream.safeGround(candidate)) {
              remember(arm, durable, ttl, candidate, t);
              continue;
            }
          }
          pendingLocations.add(t);
        }
      }

      long t = start;
      boolean served = false;
      if (tokens > 0) {
        tokens--;
        hits++;
        t = mainWork(st, arm, costs, t, costs.servePathUs(), previousPick, false);
        served = true;
      } else {
        for (int a = 0; a < arm.maxAttempts() && !served; a++) {
          attempts++;
          long candidate = nextCandidate(arm, stream, previousPick);
          previousPick = candidate;
          if (isRemembered(arm, durable, ttl, candidate, t)) {
            t = asyncWork(st, t, costs.memoryLookupUs());
            continue;
          }
          if (arm.prefilterFirst()) {
            t = asyncWork(st, t, arm.binnedReads() ? costs.binnedReadUs() : costs.regionReadColdUs());
            if (!stream.safeGround(candidate)) {
              remember(arm, durable, ttl, candidate, t);
              continue;
            }
          }
          t = chunkWork(st, arm, costs, t, arm.chunksPerCandidate(), candidate, false);
          chunkLoads += Math.round(arm.chunksPerCandidate());
          if (!arm.prefilterFirst()) {
            t = mainWork(st, arm, costs, t, costs.liveBlockCheckUs(), candidate, false);
            if (!stream.safeGround(candidate)) {
              remember(arm, durable, ttl, candidate, t);
              continue;
            }
          }
          t = mainWork(st, arm, costs, t, costs.servePathUs(), candidate, false);
          served = true;
        }
      }
      if (!served) unserved++;

      latency[r] = t - start;
      clientReady[ci] = t;
      completedAt = Math.max(completedAt, t);
    }

    return summarise(
        st, latency, completedAt, requests, attempts, chunkLoads, hits, unserved, costs);
  }

  private static long nextCandidate(Arm arm, CandidateStream stream, long previous) {
    return arm.clustered() ? stream.nextNear(previous, 8) : stream.nextUniform();
  }

  private static boolean isRemembered(
      Arm arm, Set<Long> durable, Map<Long, Long> ttl, long candidate, long now) {
    if (!arm.durableMemory()) return false;
    if (arm.memoryTtlUs() <= 0L) return durable.contains(candidate);
    Long at = ttl.get(candidate);
    // Expiry by wall clock, the blanket-TTL strategy class: knowledge is discarded on a timer
    // regardless of whether the ground it described could have changed.
    if (at == null) return false;
    if (now - at > arm.memoryTtlUs()) {
      ttl.remove(candidate);
      return false;
    }
    return true;
  }

  private static void remember(
      Arm arm, Set<Long> durable, Map<Long, Long> ttl, long candidate, long now) {
    if (!arm.durableMemory()) return;
    if (arm.memoryTtlUs() <= 0L) durable.add(candidate);
    else ttl.put(candidate, now);
  }

  /** Splits chunk cost across the tick thread and the async pool by the arm's measured share. */
  private static long chunkWork(
      State st, Arm arm, Costs costs, long t, double chunks, long candidate, boolean background) {
    double total = chunks * costs.chunkLoadUs();
    long asyncDone = asyncWork(st, t, total * arm.asyncChunkShare());
    long mainDone =
        mainWork(st, arm, costs, t, total * (1.0 - arm.asyncChunkShare()), candidate, background);
    return Math.max(asyncDone, mainDone);
  }

  /**
   * Serial tick-thread service, or on Folia the thread owning the candidate's region.
   *
   * <p>This is where the tail comes from: work is enqueued behind whatever the server is already
   * doing, so the completion time depends on utilisation rather than on the cost of the call.
   */
  private static long mainWork(
      State st, Arm arm, Costs costs, long t, double workUs, long candidate, boolean background) {
    if (workUs <= 0.0) return t;
    // Duty cycle. Plugin work on the tick thread does not get the whole wall clock: the tick still
    // has to run the rest of the server, so a job needing X microseconds of tick-thread CPU
    // occupies X / duty microseconds of elapsed time. This inflates foreground-heavy designs and
    // leaves off-tick work untouched, which is a property of the platform rather than of any
    // design - and its absence was one reason the previous model under-predicted the spread.
    double duty = Math.max(0.05, (TICK_US - costs.baseTickUs()) / (double) TICK_US);
    long work = (long) (workUs / duty);
    long cpu = (long) workUs;
    if (background) {
      // Own capacity track: occupies the tick (so it appears in MSPT) but does not enqueue a
      // player's request behind it. See State.backgroundFreeAt.
      long begin = Math.max(st.backgroundFreeAt, t);
      st.backgroundFreeAt = begin + work;
      accrueTick(st, begin, cpu);
      return st.backgroundFreeAt;
    }
    if (arm.folia()) {
      // Region threads run in parallel, but each candidate's live-block work must run on the
      // thread owning that candidate's region, and random candidates are scattered - so a
      // live-block verifier pays a region acquisition per candidate and spreads backlog across
      // many regions instead of one.
      long region = regionOf(candidate);
      long free = st.regionFreeAt.getOrDefault(region, 0L);
      long begin = Math.max(free, t);
      long end = begin + work + (long) costs.regionHopUs();
      // One episode counts once. Without this, every work item queued behind the same backlog
      // would be counted as a separate freeze and the figure would be a queue length wearing an
      // event count's name.
      if (begin - t > FREEZE_US && t >= st.regionFrozenUntil.getOrDefault(region, 0L)) {
        st.regionFreezes++;
        st.regionFrozenUntil.put(region, end);
      }
      st.regionFreeAt.put(region, end);
      accrueTick(st, begin, cpu);
      return end;
    }
    long begin = Math.max(st.mainFreeAt, t);
    st.mainFreeAt = begin + work;
    accrueTick(st, begin, cpu);
    return st.mainFreeAt;
  }

  private static long asyncWork(State st, long t, double workUs) {
    if (workUs <= 0.0) return t;
    int best = 0;
    for (int i = 1; i < st.asyncFreeAt.length; i++) {
      if (st.asyncFreeAt[i] < st.asyncFreeAt[best]) best = i;
    }
    long begin = Math.max(st.asyncFreeAt[best], t);
    st.asyncFreeAt[best] = begin + (long) workUs;
    return st.asyncFreeAt[best];
  }

  /** Folia regions are 16x16 chunk cells here; the exact size is a parameter of the platform. */
  private static long regionOf(long packed) {
    return ((long) (CandidateStream.unpackX(packed) >> 4) << 32)
        | ((CandidateStream.unpackZ(packed) >> 4) & 0xFFFFFFFFL);
  }

  private static void accrueTick(State st, long begin, long work) {
    st.tickBusy.merge(begin / TICK_US, work, Long::sum);
  }

  private static Result summarise(
      State st,
      long[] latency,
      long completedAt,
      int requests,
      long attempts,
      long chunkLoads,
      long hits,
      long unserved,
      Costs costs) {

    long[] sorted = latency.clone();
    Arrays.sort(sorted);
    double mean = 0.0;
    for (long v : latency) mean += v;
    mean /= Math.max(1, requests);

    long ticks = Math.max(1L, completedAt / TICK_US);
    double[] mspt = new double[(int) Math.min(ticks, 1_000_000L)];
    double msptSum = 0.0;
    for (int i = 0; i < mspt.length; i++) {
      mspt[i] = (costs.baseTickUs() + st.tickBusy.getOrDefault((long) i, 0L)) / 1_000.0;
      msptSum += mspt[i];
    }
    double[] msptSorted = mspt.clone();
    Arrays.sort(msptSorted);

    double seconds = completedAt / 1_000_000.0;
    double throughput = seconds > 0 ? (requests - unserved) / seconds : 0.0;
    double meanMillis = mean / 1_000.0;

    return new Result(
        throughput,
        pct(sorted, 0.50) / 1_000.0,
        pct(sorted, 0.95) / 1_000.0,
        pct(sorted, 0.99) / 1_000.0,
        pct(sorted, 0.999) / 1_000.0,
        sorted[sorted.length - 1] / 1_000.0,
        meanMillis,
        msptSum / mspt.length,
        pctD(msptSorted, 0.99),
        msptSorted[msptSorted.length - 1],
        // Per request, matching the harness's "chunks / attempt" column, where an attempt is one
        // dispatched /rtp rather than one candidate evaluated. Refiller loads count: the harness
        // attributes every load in the phase, so excluding background warm-up would understate a
        // cache design and flatter this one.
        (double) chunkLoads / Math.max(1, requests),
        (double) attempts / Math.max(1, requests),
        throughput * meanMillis / 1_000.0,
        (double) hits / Math.max(1, requests),
        count(sorted, 1_000_000L) * 1_000.0 / requests,
        count(sorted, 5_000_000L) * 1_000.0 / requests,
        st.regionFreezes,
        (double) unserved / Math.max(1, requests));
  }

  private static long pct(long[] sorted, double q) {
    return sorted[(int) Math.min(sorted.length - 1L, Math.round(q * (sorted.length - 1)))];
  }

  private static double pctD(double[] sorted, double q) {
    return sorted[(int) Math.min(sorted.length - 1L, Math.round(q * (sorted.length - 1)))];
  }

  private static long count(long[] sorted, long thresholdUs) {
    int i = 0;
    while (i < sorted.length && sorted[i] < thresholdUs) i++;
    return sorted.length - (long) i;
  }
}
