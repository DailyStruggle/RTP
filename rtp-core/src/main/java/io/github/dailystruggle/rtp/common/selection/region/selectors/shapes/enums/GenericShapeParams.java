package io.github.dailystruggle.rtp.common.selection.region.selectors.shapes.enums;

/**
 * Common parameters for all shapes
 */
public enum GenericShapeParams {
    /**
     * The UUID of the world
     */
    WORLDID,
    /**
     * The radius of the shape
     */
    RADIUS,
    /**
     * The X coordinate of the center
     */
    CX,
    /**
     * The Z coordinate of the center
     */
    CZ,
    /**
     * The minimum Y coordinate
     */
    MINY,
    /**
     * The maximum Y coordinate
     */
    MAXY,
    /**
     * Whether sky light is required
     */
    REQUIRESKYLIGHT,
    /**
     * Whether to override the world border
     */
    WORLDBORDEROVERRIDE
}


