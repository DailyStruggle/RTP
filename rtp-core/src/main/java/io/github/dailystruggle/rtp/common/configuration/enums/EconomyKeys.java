package io.github.dailystruggle.rtp.common.configuration.enums;

/** Configuration keys for economy settings */
public enum EconomyKeys {
  /** Whether to refund the cost on cancellation */
  refundOnCancel,
  /** The price for a random teleport */
  price,
  /** The price for teleporting another player */
  priceOther,
  /** The price for using parameters */
  paramsPrice,
  /** The price for selecting a biome */
  biomePrice,
  /** The minimum balance required to teleport */
  balanceFloor,
  /** The configuration version */
  version
}
