param([Parameter(Mandatory=$true)][string]$Path)

# Build mojibake search strings from raw byte sequences to avoid source-file
# encoding issues. These are the UTF-8 byte sequences produced when a file is
# UTF-8-encoded, then mis-decoded as CP1252, then re-encoded as UTF-8.
function B([int[]]$bytes) { [System.Text.Encoding]::UTF8.GetString([byte[]]$bytes) }

$pairs = @(
  ,@((B 0xC3,0xA2,0xE2,0x82,0xAC,0xE2,0x80,0x9D), [char]0x2014)  # em dash  -> —
  ,@((B 0xC3,0xA2,0xE2,0x82,0xAC,0xE2,0x80,0x9C), [char]0x2013)  # en dash  -> –
  ,@((B 0xC3,0xA2,0xE2,0x82,0xAC,0xCB,0x9C),      [char]0x2018)  # ‘
  ,@((B 0xC3,0xA2,0xE2,0x82,0xAC,0xE2,0x84,0xA2), [char]0x2019)  # ’
  ,@((B 0xC3,0xA2,0xE2,0x82,0xAC,0xC5,0x93),      [char]0x201C)  # “
  ,@((B 0xC3,0xA2,0xE2,0x82,0xAC,0xC2,0xA6),      [char]0x2026)  # …
  ,@((B 0xC3,0xA2,0xE2,0x82,0xAC,0xC2,0xA2),      [char]0x2022)  # •
  ,@((B 0xC3,0xA2,0xE2,0x80,0xA0,0xE2,0x80,0x99), [char]0x2192)  # →
  ,@((B 0xC3,0x82,0xC2,0xA7),                     [char]0x00A7)  # §
  ,@((B 0xC3,0x82,0xC2,0xB7),                     [char]0x00B7)  # ·
  ,@((B 0xC3,0x82,0xC2,0xB0),                     [char]0x00B0)  # °
  ,@((B 0xC3,0x82,0xC2,0xA0),                     ' ')           # NBSP
)

$t = [System.IO.File]::ReadAllText($Path, [System.Text.Encoding]::UTF8)
foreach ($p in $pairs) { $t = $t.Replace($p[0], [string]$p[1]) }

# Remove stray corruption fragment on its own line (e.g. "ue the ")
$t = [System.Text.RegularExpressions.Regex]::Replace($t, '(?m)^ue the\s*\r?\n', '')

$enc = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Path, $t, $enc)
Write-Output ("Fixed: " + $Path)
