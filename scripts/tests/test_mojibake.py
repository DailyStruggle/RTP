#!/usr/bin/env python3
"""Unit tests for scripts/mojibake.py and the path filter in scripts/check-mojibake.py.

Mojibake inputs are generated by mis-decoding UTF-8 as CP1252 (Latin-1 for the
five undefined bytes), so this file holds no literal corrupt text.

Run:
    python -m unittest discover -s scripts/tests -p "test_*.py"
"""

from __future__ import annotations

import importlib.util
import sys
import unittest
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SCRIPTS_DIR))

import mojibake  # noqa: E402


def mangle(text: str, times: int = 1) -> str:
    for _ in range(times):
        out = []
        for b in text.encode("utf-8"):
            try:
                out.append(bytes([b]).decode("cp1252"))
            except UnicodeDecodeError:
                out.append(chr(b))
        text = "".join(out)
    return text


SAMPLES = [
    "\u2014", "\u2013", "\u2019", "\u201c", "\u201d", "\u2026", "\u2192", "\u21d2",
    "\u00d7", "\u03b1", "\u03b2", "\u03a3", "\u2705", "\u26a1", "\u270e", "\u25b6",
    "\u250c", "\u2500", "\u2510", "\u2502", "\u2514", "\u2518", "\u00e9", "\u00a7",
    "\u00b0", "\u00b2", "\u00b7", "\u00ab", "\u00bb", "\U0001f600", "\u0105", "\u0142",
    "\u0436", "\u65e5\u672c", "\ud55c",
]

# Ordinary text whose high chars happen to sit next to each other.
LEGIT = [
    "p99 tails compress 14\u00d7\u201342\u00d7",
    "die Stra\u00df\u201c",
    "caf\u00e9, na\u00efve, \u00bfQu\u00e9?, Gr\u00fc\u00dfe",
    "\u00ab guillemets \u00bb and 2 \u00d7 3",
    "\u041f\u0440\u0438\u0432\u0435\u0442 \u65e5\u672c\u8a9e \ud55c\uad6d\uc5b4",
    "already fixed \u2014 \u2192 \u2705",
]


class RepairTest(unittest.TestCase):
    def test_single_encoded_samples_repair(self):
        for s in SAMPLES:
            with self.subTest(s=s):
                fixed, findings = mojibake.repair(f"a {mangle(s)} b")
                self.assertEqual(fixed, f"a {s} b")
                self.assertTrue(findings and all(f.replacement for f in findings))

    def test_double_encoded_samples_repair(self):
        for s in SAMPLES:
            with self.subTest(s=s):
                self.assertEqual(mojibake.repair(f"x{mangle(s, 2)}y")[0], f"x{s}y")

    def test_adjacent_sequences_are_independent(self):
        # The old hand-written map turned the vertical bar into a corner glyph.
        s = "\u2502\u2510\u2502"
        self.assertEqual(mojibake.repair(mangle(s))[0], s)

    def test_legit_text_untouched(self):
        for s in LEGIT:
            with self.subTest(s=s):
                self.assertEqual(mojibake.repair(s), (s, []))

    def test_line_endings_preserved(self):
        text = f"one {mangle(chr(0x2014))}\r\ntwo\nthree {mangle(chr(0x2026))}"
        self.assertEqual(mojibake.repair(text)[0], "one \u2014\r\ntwo\nthree \u2026")

    def test_finding_positions_are_one_based(self):
        _, findings = mojibake.repair(f"ok\nab{mangle(chr(0x2014))}")
        self.assertEqual([(f.line, f.col) for f in findings], [(2, 3)])
        self.assertEqual(findings[0].text, mangle("\u2014"))


class ResidueTest(unittest.TestCase):
    def test_lossy_marker_reported_unrepairable(self):
        # Em dash whose third byte was dropped: no valid UTF-8 left to decode.
        lossy = mangle("\u2014")[:2]
        fixed, findings = mojibake.repair(f"a {lossy} b")
        self.assertEqual(fixed, f"a {lossy} b")
        self.assertEqual([(f.col, f.replacement) for f in findings], [(3, None)])

    def test_replacement_char_reported(self):
        findings = mojibake.scan("bad \ufffd here")
        self.assertEqual([(f.text, f.replacement) for f in findings], [("\ufffd", None)])


class ExemptionTest(unittest.TestCase):
    def test_markdown_code_span_exempt(self):
        line = f"- no BOM, no `{mangle(chr(0x2014))[:2]}` / `\u00c3` / `\u00c2` markers, `{mangle(chr(0x2014))}`."
        self.assertEqual(mojibake.repair(line, markdown=True), (line, []))

    def test_code_span_not_exempt_outside_markdown(self):
        line = f"x = `{mangle(chr(0x2014))}`"
        self.assertEqual(mojibake.repair(line)[0], "x = `\u2014`")

    def test_text_outside_code_span_still_repaired(self):
        bad = mangle("\u2014")
        line = f"`{bad}` then {bad}"
        self.assertEqual(mojibake.repair(line, markdown=True)[0], f"`{bad}` then \u2014")

    def test_double_backtick_span(self):
        line = f"``a ` {mangle(chr(0x2014))}`` end"
        self.assertEqual(mojibake.repair(line, markdown=True), (line, []))

    def test_pragma_exempts_line(self):
        bad = mangle("\u2014")
        text = f"// {bad} {mojibake.PRAGMA}\n// {bad}\n"
        fixed, findings = mojibake.repair(text)
        self.assertEqual(fixed, f"// {bad} {mojibake.PRAGMA}\n// \u2014\n")
        self.assertEqual([f.line for f in findings], [2])


def _load_checker():
    spec = importlib.util.spec_from_file_location("check_mojibake", SCRIPTS_DIR / "check-mojibake.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class CheckerPathFilterTest(unittest.TestCase):
    def test_excludes_by_directory_component_only(self):
        checker = _load_checker()
        self.assertFalse(checker.is_excluded("platforms/rtp-neoforge/rtp-neoforge-common/build.gradle"))
        self.assertFalse(checker.is_excluded("scripts/release/build_front_pages.py"))
        self.assertFalse(checker.is_excluded("docs/layout/timeout.md"))
        self.assertTrue(checker.is_excluded("rtp-core/build/generated/x.java"))
        self.assertTrue(checker.is_excluded("site/index.md"))
        self.assertTrue(checker.is_excluded(".junie/AGENTS.md"))


if __name__ == "__main__":
    unittest.main()
